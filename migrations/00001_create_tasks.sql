CREATE TABLE tasks (
    -- BIGSERIAL = BIGINT + автоинкремент. Postgres заводит под капотом
    -- отдельный счётчик (sequence) и подставляет из него следующее число.
    --
    -- Почему BIG, а не просто SERIAL: SERIAL — это int4, он кончается
    -- на 2.1 млрд. Звучит как «нам столько не надо», но счётчик тратится
    -- и на откаченные вставки тоже, так что упереться реально.
    -- Переезд на BIGINT в живой таблице — долгая и болезненная операция,
    -- а лишние 4 байта на строку никого не разорят. Всегда берите BIGSERIAL.
    --
    -- PRIMARY KEY = UNIQUE + NOT NULL. Postgres автоматически создаёт под
    -- него индекс, отдельно писать CREATE INDEX для id не нужно.
    id         BIGSERIAL   PRIMARY KEY,

    -- NOT NULL — это constraint, ограничение. База сама не даст вставить
    -- строку без заголовка, даже если в коде забудут проверить.
    -- Правило простое: если поле обязательно — пишите NOT NULL. Дешевле
    -- защититься в схеме, чем ловить NULL-ы по всему приложению.
    title      TEXT        NOT NULL,

    -- DEFAULT срабатывает, когда колонку не указали в INSERT.
    -- Вместе с NOT NULL это гарантирует: done всегда true или false,
    -- третьего состояния не бывает.
    done       BOOLEAN     NOT NULL DEFAULT FALSE,

    -- TIMESTAMPTZ, а не TIMESTAMP. Разница принципиальная: TIMESTAMP хранит
    -- «14:30» без всякой привязки, и вы никогда не узнаете, чьи это 14:30.
    -- TIMESTAMPTZ приводит время к UTC при записи и разворачивает обратно
    -- при чтении. Как только у вас появится второй часовой пояс — а он
    -- появится — обычный TIMESTAMP превратится в источник багов.
    --
    -- now() — время начала транзакции, ставится базой. Не полагаемся
    -- на время приложения: у разных подов часы разойдутся.
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Индекс — это отдельная структура, которая позволяет базе не перебирать
-- всю таблицу. Аналогия: алфавитный указатель в конце книги.
--
-- Этот индекс сделан под конкретный запрос из repo.List:
--   ORDER BY created_at DESC, id DESC LIMIT $2
--
-- Порядок колонок и направление DESC совпадают с ORDER BY не случайно:
-- тогда база берёт готовую отсортированную структуру и читает из неё
-- первые 20 записей. Без индекса ей пришлось бы поднять всю таблицу
-- в память и отсортировать целиком, чтобы отдать те же 20 строк.
--
-- id вторым — чтобы порядок был устойчивым. Если две задачи создались
-- в одну микросекунду, без id их взаимный порядок не определён, и одна
-- и та же страница может отдавать их то так, то эдак.
CREATE INDEX idx_tasks_created_at ON tasks (created_at DESC, id DESC);
