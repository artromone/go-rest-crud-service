-- Вторая миграция нужна не ради колонки, а ради демонстрации: схема живёт
-- во времени, и порядок изменений зафиксирован номерами файлов.
--
-- ── Почему колонка NULLable и без DEFAULT ────────────────────────────────
--
-- Чтобы изменить схему, база берёт блокировку на таблицу. Пока блокировка
-- держится, все запросы к этой таблице — и SELECT, и INSERT — стоят
-- в очереди и ждут.
--
-- ADD COLUMN без значения по умолчанию — операция мгновенная: Postgres
-- просто дописывает строчку в описание таблицы. Существующие строки на
-- диске не трогаются вообще. Блокировка живёт миллисекунды, никто
-- не замечает.
--
-- А вот ADD COLUMN NOT NULL DEFAULT <что-то> в старых версиях Postgres
-- (до 11) заставлял базу физически переписать каждую строку таблицы,
-- чтобы проставить значение. На таблице в 50 млн строк это минуты —
-- и всё это время таблица заблокирована. Снаружи это выглядит так:
-- сервис жив, здоровье зелёное, но каждый запрос висит и отваливается
-- по таймауту. Классический способ уронить прод «безобидной миграцией».
--
-- В Postgres 11+ конкретно этот случай оптимизировали, но привычка
-- остаётся правильной, и на собеседовании про блокировки спрашивают.
-- Безопасный путь, если нужна NOT NULL колонка на большой таблице:
--   1) добавить NULLable;
--   2) отдельно, батчами, проставить значения существующим строкам;
--   3) только потом навесить NOT NULL.

-- +goose Up
-- +goose StatementBegin
ALTER TABLE tasks ADD COLUMN due_date TIMESTAMPTZ;
-- +goose StatementEnd

-- +goose Down
-- +goose StatementBegin
ALTER TABLE tasks DROP COLUMN due_date;
-- +goose StatementEnd
